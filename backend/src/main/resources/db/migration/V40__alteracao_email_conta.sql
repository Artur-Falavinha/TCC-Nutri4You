ALTER TABLE paciente ADD COLUMN versao_credencial INTEGER NOT NULL DEFAULT 0;
ALTER TABLE nutricionista ADD COLUMN versao_credencial INTEGER NOT NULL DEFAULT 0;
ALTER TABLE token_email ADD COLUMN versao_credencial INTEGER NOT NULL DEFAULT 0;

CREATE TABLE alteracao_email_pendente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INTEGER UNIQUE REFERENCES paciente (id_paciente) ON DELETE CASCADE,
    id_nutricionista INTEGER UNIQUE REFERENCES nutricionista (id_nutricionista) ON DELETE CASCADE,
    novo_email VARCHAR(100) NOT NULL,
    codigo_hash VARCHAR(64) NOT NULL,
    versao_credencial INTEGER NOT NULL,
    enviado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_alteracao_email_titular CHECK ((id_paciente IS NULL) <> (id_nutricionista IS NULL))
);
