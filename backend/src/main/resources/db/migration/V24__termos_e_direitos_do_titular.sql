CREATE TABLE IF NOT EXISTS aceite_termo (
    tipo VARCHAR(20) NOT NULL,
    titular_id INTEGER NOT NULL,
    versao VARCHAR(40) NOT NULL,
    aceito_em TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (tipo, titular_id, versao)
);

CREATE TABLE IF NOT EXISTS pedido_privacidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    titular_id INTEGER NOT NULL,
    direito VARCHAR(40) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(25) NOT NULL DEFAULT 'RECEBIDO'
);
CREATE INDEX IF NOT EXISTS idx_pedido_privacidade_titular ON pedido_privacidade (tipo, titular_id, criado_em);
