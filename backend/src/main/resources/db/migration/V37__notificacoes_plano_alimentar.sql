CREATE TABLE notificacao_plano_alimentar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INTEGER NOT NULL REFERENCES paciente(id_paciente) ON DELETE CASCADE,
    id_plano INTEGER NOT NULL UNIQUE REFERENCES plano_alimentar(id_plano) ON DELETE CASCADE,
    titulo VARCHAR(150) NOT NULL,
    atualizacao BOOLEAN NOT NULL,
    vigencia_inicio DATE NOT NULL,
    vigencia_fim DATE NOT NULL,
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_notificacao_plano_paciente ON notificacao_plano_alimentar (id_paciente, id DESC);
