CREATE TABLE notificacao_consulta_paciente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INTEGER NOT NULL REFERENCES paciente(id_paciente) ON DELETE CASCADE,
    id_consulta INTEGER NOT NULL REFERENCES consulta(id_consulta) ON DELETE CASCADE,
    versao_consulta BIGINT NOT NULL,
    tipo VARCHAR(16) NOT NULL,
    data_hora TIMESTAMP NOT NULL,
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (id_consulta, versao_consulta)
);

CREATE INDEX idx_notificacao_consulta_paciente ON notificacao_consulta_paciente (id_paciente, id DESC);
