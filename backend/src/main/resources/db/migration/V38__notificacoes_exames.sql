CREATE TABLE notificacao_exame (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_exame INTEGER NOT NULL REFERENCES exame(id_exame) ON DELETE CASCADE,
    versao_exame BIGINT NOT NULL,
    tipo VARCHAR(24) NOT NULL,
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_notificacao_exame_versao UNIQUE (id_exame, versao_exame, tipo)
);
